for n in NEW:
    if exists(n["title"], n["url"]):
        continue
    n.setdefault("keywords", [])
    n["collectedAt"] = d["archive"][DAY][0]["collectedAt"]
    items.append(n)
    added.append(n["title"])

# 排序：分数降序，同分保持原顺序
