def main():
    with open(DATA, encoding="utf-8") as f:
        d = json.load(f)

    today_list = d["archive"][TODAY]
    before = len(today_list)

    # ---- 1. 删除 ----
    kept, deleted = [], []
    for a in today_list:
        t = a.get("title", "")
        hit = next((k for k in DELETE_SUBSTR if k in t), None)
        if hit:
            deleted.append((t, hit))
        else:
            kept.append(a)

    # ---- 2. 修正 ----
    fixed_keys = set()
    for a in kept:
        t = a.get("title", "")
        patch = FIX.get(t)
        if patch:
            a.update(patch)
            fixed_keys.add(t)
    miss_fix = [k for k in FIX if k not in fixed_keys]
    if miss_fix:
        raise AssertionError(f"⚠️ FIX 键未命中（标题不完全一致）: {miss_fix}")

    # ---- 3. 补录 ----
    exist_urls = {x.get("url") for x in kept}
    exist_keys = {(x.get("title", "")[:30]) for x in kept}
    added = []
    for n in ADD:
        if n["url"] in exist_urls or n["title"][:30] in exist_keys:
            print(f"  [跳过重复] {n['title'][:40]}")
            continue
        kept.append(n)
        added.append(n)
        exist_urls.add(n["url"])
        exist_keys.add(n["title"][:30])

    # ---- 4. 排序 ----
    kept.sort(key=lambda x: -x.get("priority_score", 0))

    # ---- 5. 断言 ----
    bad_date = [x["title"] for x in kept if x.get("date") not in ALLOWED_DATES]
    assert not bad_date, f"日期越界: {bad_date}"
    bad_ca = [x["title"] for x in kept if not str(x.get("collectedAt", "")).startswith(TODAY)]
    assert not bad_ca, f"collectedAt 越界: {bad_ca}"
    lack = [x["title"] for x in kept
            if not all(x.get(k) for k in ("title", "url", "date", "source", "category", "summary"))]
    assert not lack, f"字段缺失: {lack}"
    tvs = [x["title"] for x in kept if "tv.cctv.com" in x.get("url", "")]
    if tvs:
        print(f"⚠️ 仍存在 tv.cctv 视频页（{len(tvs)} 条）: {tvs}")
    # 裸 HTML 实体检查
    import re
    ent = [x["title"] for x in kept if re.search(r"&(nbsp|amp|lt|gt|quot|middot|mdash|ndash|hellip);|&#\d+;", x.get("title", "") + (x.get("summary") or ""))]
    if ent:
        print(f"⚠️ 裸 HTML 实体残留（{len(ent)} 条）: {ent}")

    d["archive"][TODAY] = kept
    d["todayCount"] = len(kept)
    with open(DATA, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=2)

    print(f"删除 {len(deleted)} 条，修正 {len(fixed_keys)} 条，补录 {len(added)} 条")
    print(f"今日版面: {before} -> {len(kept)} 条")
    print("\n--- 删除明细 ---")
    for t, k in deleted:
        print(f"  [{k}] {t[:62]}")
    print("\n--- 补录明细 ---")
    for n in added:
        print(f"  {n['priority_score']} {n['category']} {n['title']}")
    print("\n--- 最终版面 ---")
    import collections
    print(collections.Counter(x["category"] for x in kept))
    for i, x in enumerate(kept, 1):
        print(f"{i:>2} | {x['category']} | {x['priority_score']} | {x['source']} | {x['date']} | {x['title'][:58]}")


if __name__ == "__main__":
    main()
