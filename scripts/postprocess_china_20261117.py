TODAY = "2026-11-17"
NOW = "2026-11-17 10:20:00"

with open(DATA, "r", encoding="utf-8") as f:
    data = json.load(f)

arch = data["archive"]
cur = arch[TODAY]
prev_days = [k for k in arch if k != TODAY]
prev_urls = set()
prev_title_prefix = set()
for d in prev_days:
    for it in arch[d]:
        u = (it.get("url") or "").strip().rstrip("/").lower()
        if u:
            prev_urls.add(u)
        t = re.sub(r"[^\u4e00-\u9fff]", "", it.get("title") or "")[:14]
        if t:
            prev_title_prefix.add(t)

