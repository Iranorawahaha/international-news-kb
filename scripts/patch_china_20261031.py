# 蓝湾行动 URL：tv.cctv 聚合页 -> 央视新闻正文页（若存在），否则保留但标注
def clean(s):
    s = html.unescape(s or '')
    s = s.replace('\u00a0', ' ').replace('&nbsp;', ' ')
    s = re.sub(r'<[^>]+>', '', s)
    return re.sub(r'\s+', ' ', s).strip()

for it in arr:
    it['title'] = clean(it['title'])
    it['summary'] = clean(it['summary'])
