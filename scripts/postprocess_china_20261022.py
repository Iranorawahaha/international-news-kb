def clean_entities(s: str) -> str:
    s = re.sub(r"&nbsp;|&#160;", " ", s)
    s = re.sub(r"&ldquo;|&rdquo;", '"', s)
    s = re.sub(r"&lsquo;|&rsquo;", "'", s)
    s = re.sub(r"&mdash;", "—", s)
    s = re.sub(r"&hellip;", "…", s)
    s = re.sub(r"&amp;", "&", s)
    s = re.sub(r"&(lt|gt|quot|middot|ndash);", "", s)
    s = re.sub(r"&#\d+;", "", s)
    return re.sub(r"[ \t]{2,}", " ", s).strip()


