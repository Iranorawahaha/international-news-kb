P = os.path.join(BASE, "data", "diplomatic-affairs.json")
CST = timezone(timedelta(hours=8))

with open(P, encoding="utf-8") as f:
    d = json.load(f)

def get(mod, i):
    for x in d["modules"][mod]["items"]:
        if x["id"] == i:
            return x
    raise KeyError(i)

def add_sources(it, pairs):
    have = {s.get("url") for s in it.get("sources", [])}
    for t, u in pairs:
        if u not in have:
            it.setdefault("sources", []).append({"title": t, "url": u})
            have.add(u)

